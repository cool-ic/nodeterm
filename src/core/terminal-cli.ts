// Local terminal entry points: the CLI gets this pane's identity, even when it was
// started by hand. Codex must not borrow another pane's auto-started daemon.
import fs from 'node:fs'
import path from 'node:path'
import { findInPathString } from './exec-path'
import { shellSingleQuote } from '../shared/shell-quote'
import { CODEX_NO_DAEMON_HELP_ERE } from '../shared/agents/codex-daemon'
import { renameAtomicSync, tempNameFor } from './fs-atomic'

function publishScript(file: string, body: string): void {
  const tmp = tempNameFor(file)
  try {
    fs.writeFileSync(tmp, body, { mode: 0o700 })
    renameAtomicSync(tmp, file)
  } finally {
    try { fs.rmSync(tmp, { force: true }) } catch { /* preserve the publication error */ }
  }
}

export const NODE_SCOPE_ENV = [
  'NODETERM_NODE_ID', 'NODETERM_AGENT_ID', 'NODETERM_CANVAS_CONTROL',
  'NODETERM_HOOK_ENDPOINT', 'NODETERM_HOOK_SOCK', 'NODETERM_HOOK_VERSION',
  'NODETERM_PERM_WAIT_SECS', 'NODETERM_HOOK_TOKEN', 'NODETERM_HOOK_PORT'
] as const

export function terminalCliScript(agent: 'codex' | 'qoder', executable: string): string {
  const bin = shellSingleQuote(executable)
  return `#!/bin/sh
export NODETERM_AGENT_ID=${agent}
${agent === 'codex' ? `for nt_arg in "$@"; do
  case "$nt_arg" in --) break ;; --no-daemon|--remote|--remote=*) exec ${bin} "$@" ;; esac
done
if ${bin} --help 2>/dev/null | grep -q -E '${CODEX_NO_DAEMON_HELP_ERE}'; then
  exec ${bin} --no-daemon "$@"
fi
` : ''}exec ${bin} "$@"
`
}

/** Scoped to nodeterm's local terminal PATH; never replaces the user's installed CLI. */
export function ensureTerminalCliBin(userDataDir: string, searchPath: string): string | null {
  if (process.platform === 'win32') return null
  const dir = path.join(userDataDir, 'terminal-cli')
  const cleanPath = searchPath.split(path.delimiter).filter(p => path.resolve(p) !== path.resolve(dir)).join(path.delimiter)
  let installed = false
  for (const [name, agent, realName] of [
    ['codex', 'codex', 'codex'], ['qoder', 'qoder', 'qodercli'], ['qodercli', 'qoder', 'qodercli']
  ] as const) {
    const bin = findInPathString(realName, cleanPath)
    if (!bin) continue
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 })
    const file = path.join(dir, name), body = terminalCliScript(agent, bin)
    let prior: string | undefined
    try { prior = fs.readFileSync(file, 'utf8') } catch { /* first install */ }
    if (prior !== body) {
      publishScript(file, body)
    }
    installed = true
  }
  return installed ? dir : null
}

/** Zsh startup tools such as fnm prepend PATH again at the first prompt. Keep our
 * entry points as shell-local functions after sourcing the user's real startup
 * files. Explicit user functions/aliases still win. No user dotfile is edited. */
export function ensureTerminalZsh(userDataDir: string, bin: string): string {
  const dir = path.join(userDataDir, 'terminal-zsh')
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 })
  const functions = ['codex', 'qoder', 'qodercli'].filter(name => fs.existsSync(path.join(bin, name))).map(name =>
    `if (( ! $+aliases[${name}] && ! $+functions[${name}] )); then
  function ${name}() { ${shellSingleQuote(path.join(bin, name))} "$@"; }
fi`
  ).join('\n')
  for (const rc of ['.zshenv', '.zprofile', '.zshrc', '.zlogin', '.zlogout']) {
    const body = `# Generated by nodeterm, scoped to this terminal.
ZDOTDIR="\${NODETERM_USER_ZDOTDIR:-$HOME}"
if [[ -r "$ZDOTDIR/${rc}" ]]; then builtin source "$ZDOTDIR/${rc}"; fi
export NODETERM_USER_ZDOTDIR="\${ZDOTDIR:-$HOME}"
export ZDOTDIR=${shellSingleQuote(dir)}
${rc === '.zshrc' || rc === '.zlogin' ? functions : ''}
`
    publishScript(path.join(dir, rc), body)
  }
  return dir
}
